#!/usr/bin/env python3
"""Install the standalone expression policy without touching other tools or plugins."""
import argparse
import datetime
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile

import expression_policy

SOURCE = Path(__file__).resolve().parent
HOME = Path.home()
PREFIX = HOME / '.local/share/expression-policy'
BIN = HOME / '.local/bin/xpctl'
CONFIG = HOME / '.config/expression-policy'
STATE = HOME / '.local/state/expression-policy'
MARKER = 'expression-policy'
EVENTS = ('SessionStart', 'UserPromptSubmit', 'Stop')
MODULES = ('platform_support.py', 'codex_hook_admin.py', 'expression_policy.py')
LEGACY = HOME / '.local/share/claude-codex-loop/expression.py'


def copy_atomic(source, target):
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.expression-install-', dir=str(target.parent))
    os.close(fd)
    try:
        shutil.copy2(source, temporary)
        os.replace(temporary, target)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def read_json(path):
    return json.loads(path.read_text(encoding='utf-8-sig')) if path.exists() else {}


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.expression-install-', dir=str(path.parent))
    os.close(fd)
    try:
        Path(temporary).write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def block(path, body, marker=MARKER):
    start, end = '<!-- BEGIN ' + marker + ' -->', '<!-- END ' + marker + ' -->'
    original = path.read_text(encoding='utf-8') if path.exists() else ''
    if start in original:
        a = original.index(start)
        b = original.index(end, a) + len(end)
        updated = original[:a] + start + '\n' + body + '\n' + end + original[b:]
    else:
        updated = original.rstrip() + '\n\n' + start + '\n' + body + '\n' + end + '\n'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(updated, encoding='utf-8')


def existing_block(path):
    if not path.exists():
        return None
    text = path.read_text(encoding='utf-8')
    start, end = '<!-- BEGIN ' + MARKER + ' -->', '<!-- END ' + MARKER + ' -->'
    if start not in text:
        return None
    if end not in text:
        raise ValueError('Incomplete expression-policy block in ' + str(path))
    a = text.index(start)
    return text[a:text.index(end, a) + len(end)]


def should_replace(existing):
    # ccl style: previous prototype; xpctl: generated by this project.
    return existing is None or 'ccl style' in existing or 'xpctl' in existing


def install_global(path, client):
    existing = existing_block(path)
    if not should_replace(existing):
        return False
    template = (SOURCE/'rules/global-policy.md').read_text(encoding='utf-8')
    body = template.replace('@RULES@', (CONFIG/'rules.md').as_posix()).replace('@CLIENT@', client)
    block(path, body)
    return True


def install_config():
    CONFIG.mkdir(parents=True, exist_ok=True)
    bundled = PREFIX/'rules/expression.md'
    bundled.parent.mkdir(parents=True, exist_ok=True)
    copy_atomic(SOURCE/'rules/expression.md', bundled)
    if not (CONFIG/'rules.md').exists():
        copy_atomic(bundled, CONFIG/'rules.md')
    guide = (SOURCE/'docs/control.md').read_text(encoding='utf-8')
    (CONFIG/'CONTROL.md').write_text(guide.replace('(../rules/expression.md)', '(' + bundled.as_uri() + ')'),
                                     encoding='utf-8')


def hook_handler(client):
    command = expression_policy.hook_command(sys.executable, PREFIX/'expression_policy.py', client)
    if not expression_policy.is_hook_command(command, PREFIX/'expression_policy.py', client):
        raise ValueError('Python/helper paths contain unsupported shell metacharacters')
    return {'type': 'command', 'command': command, 'timeout': 5}


def remove_handlers(settings, program, client=None):
    hooks = settings.get('hooks', {})
    changed = False
    for event in EVENTS:
        groups = []
        for group in hooks.get(event, []):
            kept = [item for item in group.get('hooks', [])
                    if not expression_policy.is_hook_command(item.get('command'), program, client)]
            if len(kept) != len(group.get('hooks', [])):
                changed = True
            if kept:
                groups.append(dict(group, hooks=kept))
        if groups:
            hooks[event] = groups
        elif event in hooks:
            hooks.pop(event)
            changed = True
    return changed


def configure_hooks(path, client):
    settings = read_json(path)
    # Migrate only the old prototype command; leave CCL mode hooks and other plugins intact.
    remove_handlers(settings, LEGACY, client)
    hooks = settings.setdefault('hooks', {})
    handler = hook_handler(client)
    for event in EVENTS:
        groups = hooks.setdefault(event, [])
        matches = [(group, index) for group in groups for index, item in enumerate(group.get('hooks', []))
                   if expression_policy.is_hook_command(item.get('command'), PREFIX/'expression_policy.py', client)]
        if matches:
            group, index = matches[0]
            group['hooks'][index] = dict(group['hooks'][index], **handler)
            for extra_group, extra_index in reversed(matches[1:]):
                extra_group['hooks'].pop(extra_index)
                if not extra_group['hooks']:
                    groups.remove(extra_group)
        else:
            groups.append({'hooks': [dict(handler)]})
    write_json(path, settings)
    return settings


def install_prefix():
    PREFIX.mkdir(parents=True, exist_ok=True)
    for name in MODULES:
        copy_atomic(SOURCE/name, PREFIX/name)
    BIN.parent.mkdir(parents=True, exist_ok=True)
    python, program = Path(sys.executable).as_posix(), (PREFIX/'expression_policy.py').as_posix()
    if os.name == 'nt':
        BIN.with_suffix('.cmd').write_text('@echo off\n"' + python + '" -X utf8 "' + program + '" %*\n',
                                           encoding='utf-8')
    else:
        BIN.write_bytes(('#!/bin/sh\nexec "' + python + '" -X utf8 "' + program + '" "$@"\n').encode('utf-8'))
        BIN.chmod(0o700)


def backup_paths():
    stamp = datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
    backup = STATE/'backups'/stamp
    targets = [HOME/'.claude/settings.json', HOME/'.claude/CLAUDE.md',
               HOME/'.codex/hooks.json', HOME/'.codex/AGENTS.md',
               CONFIG/'rules.md', CONFIG/'CONTROL.md', BIN, BIN.with_suffix('.cmd')]
    targets += [PREFIX/name for name in MODULES]
    targets += [PREFIX/'rules/expression.md']
    backup.mkdir(parents=True)
    manifest = []
    for index, path in enumerate(targets):
        saved = backup/str(index)
        manifest.append({'path': str(path), 'existed': path.exists(), 'backup': str(saved)})
        if path.exists():
            shutil.copy2(path, saved)
    (backup/'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    return backup, manifest


def rollback(manifest):
    for item in manifest:
        path = Path(item['path'])
        if item['existed']:
            path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item['backup'], path)
        elif path.exists():
            path.unlink()
    for directory in (PREFIX/'rules', PREFIX, CONFIG):
        try:
            directory.rmdir()
        except OSError:
            pass


def install():
    if sys.version_info < (3, 9):
        raise SystemExit('expression-policy requires Python 3.9+')
    os.umask(0o077)
    backup, manifest = backup_paths()
    try:
        install_config()
        install_prefix()
        configure_hooks(HOME/'.claude/settings.json', 'claude')
        configure_hooks(HOME/'.codex/hooks.json', 'codex')
        updated = [str(path) for path in (HOME/'.claude/CLAUDE.md', HOME/'.codex/AGENTS.md')
                   if install_global(path, 'claude' if 'CLAUDE' in path.name else 'codex')]
        print(json.dumps({'installed': str(BIN), 'rules': str(CONFIG/'rules.md'), 'backup': str(backup),
                          'global_blocks_updated': updated, 'hooks': list(EVENTS),
                          'codex_trust': 'Review ~/.codex/hooks.json in Codex /hooks, or run the installed '
                                         'codex_hook_admin.py --approve after inspection. No trust is granted here.'},
                         ensure_ascii=False))
    except BaseException:
        rollback(manifest)
        raise


def remove_block(path):
    if not path.exists():
        return
    text = path.read_text(encoding='utf-8')
    start, end = '<!-- BEGIN ' + MARKER + ' -->', '<!-- END ' + MARKER + ' -->'
    if start in text and end in text:
        a = text.index(start)
        b = text.index(end, a) + len(end)
        path.write_text((text[:a].rstrip() + '\n' + text[b:].lstrip()).strip() + '\n', encoding='utf-8')


def uninstall(purge=False):
    for path in (HOME/'.claude/settings.json', HOME/'.codex/hooks.json'):
        if path.exists():
            settings = read_json(path)
            if remove_handlers(settings, PREFIX/'expression_policy.py'):
                write_json(path, settings)
    for path in (HOME/'.claude/CLAUDE.md', HOME/'.codex/AGENTS.md'):
        remove_block(path)
    if PREFIX.exists():
        shutil.rmtree(PREFIX)
    for path in (BIN, BIN.with_suffix('.cmd')):
        if path.exists():
            path.unlink()
    if purge:
        for path in (CONFIG, STATE):
            if path.exists():
                shutil.rmtree(path)
    print(json.dumps({'uninstalled': True, 'purged': purge,
                      'kept': [] if purge else [str(CONFIG), str(STATE)]}, ensure_ascii=False))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--uninstall', action='store_true', help='Remove only this tool\'s hooks and files')
    parser.add_argument('--purge', action='store_true', help='With --uninstall, also remove rules and session state')
    args = parser.parse_args()
    uninstall(args.purge) if args.uninstall else install()
